from __future__ import annotations

import textwrap

from . import __version__
from .analyzer import Analysis
from .baseline import ATTRIBUTION, BaselineResult
from .rules import RULE_CATALOG

WIDTH = 96


def _heading(title: str) -> str:
    return f"{title}\n{'=' * WIDTH}"


def render_report(analysis: Analysis, baseline: BaselineResult, source: str) -> str:
    """Render an analysis report as deterministic plain text."""
    counts = analysis.counts()
    lines = [
        _heading(f"planradius {__version__} — {ATTRIBUTION}"),
        f"Plan          : {source}",
        f"Engine format : {analysis.plan.format_version}",
        f"Engine version: {analysis.plan.terraform_version}",
        f"Resources     : {len(analysis.plan.resources)} "
        f"({len(analysis.plan.changed_resources)} changed)",
        f"Graph         : {len(analysis.graph.nodes)} nodes, "
        f"{sum(len(analysis.graph.dependencies_of(n)) for n in analysis.graph.nodes)} edges",
        "Findings      : "
        f"{counts['critical']} critical / {counts['high']} high / "
        f"{counts['medium']} medium / {counts['low']} low",
        f"Gate          : {len(baseline.active)} active, "
        f"{len(baseline.acknowledged)} acknowledged, {len(baseline.stale)} stale baseline entries",
        "-" * WIDTH,
    ]
    if not analysis.findings:
        lines.append("No risks detected by the enabled rule set.")
    for finding in analysis.findings:
        state = (
            "ACK"
            if finding.fingerprint not in {item.fingerprint for item in baseline.active}
            else "NEW"
        )
        lines.extend(
            [
                f"[{finding.severity.upper():8}] {finding.rule_id} {finding.title} ({state})",
                f"  resource    : {finding.resource}",
                textwrap.fill(
                    f"detail      : {finding.detail}",
                    width=WIDTH,
                    initial_indent="  ",
                    subsequent_indent=" " * 14,
                ),
                textwrap.fill(
                    f"remediation : {finding.remediation}",
                    width=WIDTH,
                    initial_indent="  ",
                    subsequent_indent=" " * 14,
                ),
                f"  fingerprint : {finding.fingerprint}",
                "",
            ]
        )
    if baseline.stale:
        lines.append("Stale baseline entries: " + ", ".join(baseline.stale))
    lines.extend(["-" * WIDTH, f"Report generated by Baysöz Labs planradius — {ATTRIBUTION}"])
    return "\n".join(lines)


def render_rules() -> str:
    """Render the built-in rule catalog."""
    lines = [_heading(f"planradius rule catalog — {ATTRIBUTION}")]
    for rule in RULE_CATALOG:
        lines.append(f"{rule['id']}  {rule['title']} [{rule['severity']}]")
        lines.append(
            textwrap.fill(f"    {rule['description']}", width=WIDTH, subsequent_indent=" " * 4)
        )
    lines.append(f"Attribution: {ATTRIBUTION}")
    return "\n".join(lines)


def render_explain(
    address: str,
    resource_detail: dict[str, object],
    blast_radius: tuple[str, ...],
    paths: tuple[str, ...],
) -> str:
    """Render the graph and permission explanation for a resource."""
    lines = [
        _heading(f"planradius explain: {address} — {ATTRIBUTION}"),
        f"type          : {resource_detail['type']}",
        f"actions       : {resource_detail['actions']}",
        f"dependencies  : {', '.join(resource_detail['dependencies']) or '<none>'}",
        f"dependents    : {', '.join(resource_detail['dependents']) or '<none>'}",
        f"blast radius  : {len(blast_radius)} resource(s)",
    ]
    for item in blast_radius[:20]:
        lines.append(f"  -> {item}")
    lines.append(f"escalation paths: {len(paths)}")
    for path in paths:
        lines.append(f"  -> {path}")
    lines.append(f"Attribution: {ATTRIBUTION}")
    return "\n".join(lines)
